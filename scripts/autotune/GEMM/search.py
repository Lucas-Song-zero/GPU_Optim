#!/usr/bin/env python3
"""Search driver for the GEMM autotuner.

Strategy (single-compile + runtime switch): the tunable kernels are templated on
compile-time ints, so we cannot enumerate configs in a runtime loop.  Instead
we *generate* one self-contained ``.cu`` whose ``launch(cfg, ...)`` switches
over every valid config, compile it once, run it once per problem size, and
parse per-config GFLOPS from stdout into ``results.json``.

Two kernels are supported:

    * ``--kernel tunable`` : 2D block-tiling kernel (src/GEMM/7_autotune.cuh)
    * ``--kernel warp``    : warp-tiling kernel (src/GEMM/9_autotune_more.cuh)

Usage::

    python search.py                                # tunable, default sizes
    python search.py --kernel warp --sizes 512,1024 # warp tiling
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]  # scripts/autotune/GEMM -> repo root
sys.path.insert(0, str(HERE))

import constraints  # noqa: E402

BUILD_DIR = REPO / "build"
AUTOTUNE_BUILD = BUILD_DIR / "autotune"

BENCH_CU = AUTOTUNE_BUILD / "autotune_bench.cu"
BENCH_BIN = AUTOTUNE_BUILD / "autotune_bench"
RESULTS_JSON = HERE / "results.json"

DEFAULT_SIZES = (128, 256, 512, 1024, 2048, 4096)
DEFAULT_NVCC = "/usr/local/cuda-13.3/bin/nvcc"
DEFAULT_ARCH = "sm_120"

# Config fields printed after the leading cfg index, per kernel.
TUNE_FIELDS = ("threads", "BM", "BN", "BK", "TM", "TN")
WARP_FIELDS = ("threads", "BM", "BN", "BK", "WM", "WN", "LaneSizeN", "TM", "TN")

NCU = "/usr/local/cuda-13.3/bin/ncu"
PROFILE_CU = AUTOTUNE_BUILD / "profile_best.cu"
PROFILE_BIN = AUTOTUNE_BUILD / "profile_best"
PROFILE_DIR = REPO / "results" / "profiles"
PROFILE_REP_DIR = PROFILE_DIR / "ncu-rep"
PROFILE_TXT_DIR = PROFILE_DIR / "txt"
PROFILE_CSV_DIR = PROFILE_DIR / "csv"
PROFILE_SECTIONS = (
    "SpeedOfLight",
    "ComputeWorkloadAnalysis",
    "MemoryWorkloadAnalysis",
    "Occupancy",
    "SchedulerStats",
    "WarpStateStats",
)


def _preamble(kernel_include: str, extra_defines: list[str] | None = None) -> list[str]:
    lines = ["// Auto-generated by scripts/autotune/GEMM/search.py. Do not edit.",
             "#include <cmath>",
             "#include <cstdio>",
             "#include <cstdlib>",
             ""]
    for d in extra_defines or []:
        lines.append(d)
    lines.append(f'#include "{kernel_include}"')
    lines.append("")
    return lines


def _emit_main(fields: tuple[str, ...]) -> list[str]:
    """Emit the CPU reference + main() harness, shared by both kernels."""
    int_fmt = " ".join(["%d"] * len(fields))
    args = ", ".join(f"CFG[cfg].{f}" for f in fields)

    L = [
        "static float randf() { return (float)(rand() % 1000) / 100.0f - 5.0f; }",
        "",
        "static void gemm_cpu(int M, int N, int K, float alpha, const float *A,",
        "                     const float *B, float beta, const float *C0, float *Cref) {",
        "    for (int i = 0; i < M; ++i)",
        "        for (int j = 0; j < N; ++j) {",
        "            float s = 0.0f;",
        "            for (int k = 0; k < K; ++k) s += A[i * K + k] * B[k * N + j];",
        "            Cref[i * N + j] = alpha * s + beta * C0[i * N + j];",
        "        }",
        "}",
        "",
        "static bool close_enough(const float *a, const float *b, int n) {",
        "    for (int i = 0; i < n; ++i) {",
        "        float diff = fabsf(a[i] - b[i]);",
        "        float thre = 1e-4f * fabsf(b[i]) + 1e-3f;",
        "        if (diff > thre) return false;",
        "    }",
        "    return true;",
        "}",
        "",
        "int main(int argc, char **argv) {",
        '    if (argc < 4) { fprintf(stderr, "usage: %s M N K [repeat]\\n", argv[0]); return 1; }',
        "    int M = atoi(argv[1]), N = atoi(argv[2]), K = atoi(argv[3]);",
        "    int repeat = argc > 4 ? atoi(argv[4]) : 20;",
        "    float alpha = 0.5f, beta = 3.0f;",
        "",
        "    size_t szA = (size_t)M * K, szB = (size_t)K * N, szC = (size_t)M * N;",
        "    float *A = (float*)malloc(szA * sizeof(float));",
        "    float *B = (float*)malloc(szB * sizeof(float));",
        "    float *C0 = (float*)malloc(szC * sizeof(float));",
        "    float *Cref = (float*)malloc(szC * sizeof(float));",
        "    float *C = (float*)malloc(szC * sizeof(float));",
        "    srand(42);",
        "    for (size_t i = 0; i < szA; ++i) A[i] = randf();",
        "    for (size_t i = 0; i < szB; ++i) B[i] = randf();",
        "    for (size_t i = 0; i < szC; ++i) C0[i] = randf();",
        "",
        "    float *dA, *dB, *dC;",
        "    cudaMalloc(&dA, szA * sizeof(float));",
        "    cudaMalloc(&dB, szB * sizeof(float));",
        "    cudaMalloc(&dC, szC * sizeof(float));",
        "    cudaMemcpy(dA, A, szA * sizeof(float), cudaMemcpyHostToDevice);",
        "    cudaMemcpy(dB, B, szB * sizeof(float), cudaMemcpyHostToDevice);",
        "    gemm_cpu(M, N, K, alpha, A, B, beta, C0, Cref);",
        "",
        "    cudaEvent_t beg, end;",
        "    cudaEventCreate(&beg); cudaEventCreate(&end);",
        "",
        "    for (int cfg = 0; cfg < NUM_CONFIGS; ++cfg) {",
        "        cudaMemcpy(dC, C0, szC * sizeof(float), cudaMemcpyHostToDevice);",
        "        launch(cfg, M, N, K, alpha, dA, dB, beta, dC);",
        "        cudaError_t err = cudaDeviceSynchronize();",
        "        if (err != cudaSuccess) {",
        f'            printf("CFG %d {int_fmt} 0.000000 0.0 ERROR(%s)\\n",',
        f"                   cfg, {args}, cudaGetErrorString(err));",
        "            fflush(stdout); continue;",
        "        }",
        "        cudaMemcpy(C, dC, szC * sizeof(float), cudaMemcpyDeviceToHost);",
        "        bool ok = close_enough(C, Cref, (int)szC);",
        "",
        "        cudaEventRecord(beg);",
        "        for (int j = 0; j < repeat; ++j) launch(cfg, M, N, K, alpha, dA, dB, beta, dC);",
        "        cudaEventRecord(end);",
        "        cudaEventSynchronize(end);",
        "        float ms = 0.0f; cudaEventElapsedTime(&ms, beg, end); ms /= repeat;",
        "        double gflops = 2.0 * (double)M * N * K / (ms * 1e-3) / 1e9;",
        "",
        f'        printf("CFG %d {int_fmt} %.6f %.1f %s\\n",',
        f'               cfg, {args}, ms, gflops, ok ? "OK" : "BAD");',
        "        fflush(stdout);",
        "    }",
        "",
        "    free(A); free(B); free(C0); free(Cref); free(C);",
        "    cudaFree(dA); cudaFree(dB); cudaFree(dC);",
        "    cudaEventDestroy(beg); cudaEventDestroy(end);",
        "    return 0;",
        "}",
    ]
    return L


def render_tunable(cfgs, vec: int) -> str:
    """Render the 2D block-tiling benchmark (kernel 7_autotune)."""
    lines = _preamble("GEMM/7_autotune.cuh", [f"#define VEC_CONFIG {vec}"])
    lines.append("struct CfgInfo { int threads, BM, BN, BK, TM, TN; };")
    lines.append("static const CfgInfo CFG[] = {")
    for c in cfgs:
        lines.append(f"    {{{c.threads}, {c.BM}, {c.BN}, {c.BK}, {c.TM}, {c.TN}}},")
    lines.append("};")
    lines.append("static const int NUM_CONFIGS = (int)(sizeof(CFG) / sizeof(CFG[0]));")
    lines.append("")

    lines.append("static void launch(int cfg, int M, int N, int K, float alpha,")
    lines.append("                   float *A, float *B, float beta, float *C) {")
    lines.append("    switch (cfg) {")
    for i, c in enumerate(cfgs):
        lines.append(f"        case {i}: {{")
        lines.append(
            f"            constexpr int T = {c.threads}, BM = {c.BM}, BN = {c.BN}, "
            f"BK = {c.BK}, TM = {c.TM}, TN = {c.TN};"
        )
        lines.append("            dim3 grid((M + BM - 1) / BM, (N + BN - 1) / BN);")
        lines.append(
            "            gemm_tunable<T, BM, BN, BK, TM, TN>"
            "<<<grid, T>>>(M, N, K, alpha, A, B, beta, C);"
        )
        lines.append("            break;")
        lines.append("        }")
    lines.append("        default: break;")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines += _emit_main(TUNE_FIELDS)
    return "\n".join(lines) + "\n"


def render_warp(cfgs) -> str:
    """Render the warp-tiling benchmark (kernel 9_autotune_more)."""
    lines = _preamble("GEMM/9_autotune_more.cuh")
    lines.append(
        "struct CfgInfo { int threads, BM, BN, BK, WM, WN, LaneSizeN, TM, TN; };"
    )
    lines.append("static const CfgInfo CFG[] = {")
    for c in cfgs:
        lines.append(
            f"    {{{c.threads}, {c.BM}, {c.BN}, {c.BK}, {c.WM}, {c.WN}, "
            f"{c.LaneSizeN}, {c.TM}, {c.TN}}},"
        )
    lines.append("};")
    lines.append("static const int NUM_CONFIGS = (int)(sizeof(CFG) / sizeof(CFG[0]));")
    lines.append("")

    lines.append("static void launch(int cfg, int M, int N, int K, float alpha,")
    lines.append("                   float *A, float *B, float beta, float *C) {")
    lines.append("    switch (cfg) {")
    for i, c in enumerate(cfgs):
        lines.append(f"        case {i}: {{")
        lines.append(
            f"            constexpr int BM = {c.BM}, BN = {c.BN}, BK = {c.BK}, "
            f"WM = {c.WM}, WN = {c.WN}, LaneSizeN = {c.LaneSizeN}, "
            f"TM = {c.TM}, TN = {c.TN};"
        )
        lines.append("            dim3 grid((M + BM - 1) / BM, (N + BN - 1) / BN);")
        lines.append(
            f"            gemm_warp_tunable<BM, BN, BK, WM, WN, LaneSizeN, TM, TN>"
            f"<<<grid, {c.threads}>>>(M, N, K, alpha, A, B, beta, C);"
        )
        lines.append("            break;")
        lines.append("        }")
    lines.append("        default: break;")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines += _emit_main(WARP_FIELDS)
    return "\n".join(lines) + "\n"


def _render_profile_main(constexpr: str, launch: str) -> str:
    """Emit a single-config main() with cudaProfilerStart/Stop for ncu."""
    lines = [
        "#include <cuda_profiler_api.h>",
        "",
        "static float randf() { return (float)(rand() % 1000) / 100.0f - 5.0f; }",
        "",
        "int main(int argc, char **argv) {",
        '    if (argc < 4) { fprintf(stderr, "usage: %s M N K [warmup]\\n", argv[0]); return 1; }',
        "    int M = atoi(argv[1]), N = atoi(argv[2]), K = atoi(argv[3]);",
        "    int warmup = argc > 4 ? atoi(argv[4]) : 10;",
        "    float alpha = 0.5f, beta = 3.0f;",
        "",
        "    size_t szA = (size_t)M * K, szB = (size_t)K * N, szC = (size_t)M * N;",
        "    float *A = (float*)malloc(szA * sizeof(float));",
        "    float *B = (float*)malloc(szB * sizeof(float));",
        "    float *C = (float*)malloc(szC * sizeof(float));",
        "    srand(42);",
        "    for (size_t i = 0; i < szA; ++i) A[i] = randf();",
        "    for (size_t i = 0; i < szB; ++i) B[i] = randf();",
        "    for (size_t i = 0; i < szC; ++i) C[i] = randf();",
        "    float *dA, *dB, *dC;",
        "    cudaMalloc(&dA, szA * sizeof(float));",
        "    cudaMalloc(&dB, szB * sizeof(float));",
        "    cudaMalloc(&dC, szC * sizeof(float));",
        "    cudaMemcpy(dA, A, szA * sizeof(float), cudaMemcpyHostToDevice);",
        "    cudaMemcpy(dB, B, szB * sizeof(float), cudaMemcpyHostToDevice);",
        "    cudaMemcpy(dC, C, szC * sizeof(float), cudaMemcpyHostToDevice);",
        "",
        constexpr,
        "    dim3 grid((M + BM - 1) / BM, (N + BN - 1) / BN);",
        "",
        "    for (int i = 0; i < warmup; ++i) {",
        f"        {launch}",
        "    }",
        "    cudaDeviceSynchronize();",
        "    cudaProfilerStart();",
        f"    {launch}",
        "    cudaDeviceSynchronize();",
        "    cudaProfilerStop();",
        "",
        "    free(A); free(B); free(C);",
        "    cudaFree(dA); cudaFree(dB); cudaFree(dC);",
        "    return 0;",
        "}",
    ]
    return "\n".join(lines) + "\n"


def render_profile_warp(cfg: dict) -> str:
    lines = _preamble("GEMM/9_autotune_more.cuh")
    constexpr = (
        f"    constexpr int BM = {cfg['BM']}, BN = {cfg['BN']}, BK = {cfg['BK']}, "
        f"WM = {cfg['WM']}, WN = {cfg['WN']}, LaneSizeN = {cfg['LaneSizeN']}, "
        f"TM = {cfg['TM']}, TN = {cfg['TN']};"
    )
    launch = ("gemm_warp_tunable<BM, BN, BK, WM, WN, LaneSizeN, TM, TN>"
              f"<<<grid, {cfg['threads']}>>>(M, N, K, alpha, dA, dB, beta, dC);")
    return "\n".join(lines) + "\n" + _render_profile_main(constexpr, launch)


def render_profile_tunable(cfg: dict, vec: int) -> str:
    lines = _preamble("GEMM/7_autotune.cuh", [f"#define VEC_CONFIG {vec}"])
    constexpr = (
        f"    constexpr int T = {cfg['threads']}, BM = {cfg['BM']}, BN = {cfg['BN']}, "
        f"BK = {cfg['BK']}, TM = {cfg['TM']}, TN = {cfg['TN']};"
    )
    launch = ("gemm_tunable<T, BM, BN, BK, TM, TN>"
              "<<<grid, T>>>(M, N, K, alpha, dA, dB, beta, dC);")
    return "\n".join(lines) + "\n" + _render_profile_main(constexpr, launch)


def compile_bench(nvcc: str, arch: str) -> None:
    cmd = [
        nvcc,
        f"-arch={arch}",
        "-std=c++20",
        "-O3",
        "-I", str(REPO / "src"),
        "-o", str(BENCH_BIN),
        str(BENCH_CU),
    ]
    print("compiling:", " ".join(cmd))
    subprocess.run(cmd, cwd=str(REPO), check=True)


def run_bench(size: int, repeat: int, fields: tuple[str, ...]) -> list[dict]:
    cmd = [str(BENCH_BIN), str(size), str(size), str(size), str(repeat)]
    proc = subprocess.run(cmd, cwd=str(REPO), capture_output=True, text=True)
    if proc.returncode != 0:
        print(proc.stderr, file=sys.stderr)
        raise RuntimeError(f"benchmark failed for size {size}")

    records = []
    for line in proc.stdout.splitlines():
        parts = line.split(maxsplit=4 + len(fields))
        if not parts or parts[0] != "CFG" or len(parts) < 5 + len(fields):
            continue
        cfg = int(parts[1])
        vals = [int(x) for x in parts[2:2 + len(fields)]]
        ms = float(parts[2 + len(fields)])
        gflops = float(parts[3 + len(fields)])
        status = parts[4 + len(fields)]
        rec = {"size": size, "cfg": cfg}
        rec.update(dict(zip(fields, vals)))
        rec.update({"ms": ms, "gflops": gflops, "ok": status == "OK"})
        records.append(rec)
    return records


def compile_profile(nvcc: str, arch: str) -> None:
    cmd = [
        nvcc,
        f"-arch={arch}",
        "-std=c++20",
        "-O3",
        "-lineinfo",
        "-I", str(REPO / "src"),
        "-o", str(PROFILE_BIN),
        str(PROFILE_CU),
    ]
    print("compiling:", " ".join(cmd))
    subprocess.run(cmd, cwd=str(REPO), check=True)


def run_profile(size: int, kernel: str, warmup: int) -> None:
    PROFILE_REP_DIR.mkdir(parents=True, exist_ok=True)
    PROFILE_TXT_DIR.mkdir(parents=True, exist_ok=True)
    PROFILE_CSV_DIR.mkdir(parents=True, exist_ok=True)
    name = f"autotune_best_{kernel}_{size}"
    base = PROFILE_REP_DIR / name
    cmd = [NCU, "--profile-from-start", "off", "--launch-count", "1"]
    for s in PROFILE_SECTIONS:
        cmd += ["--section", s]
    cmd += ["--force-overwrite", "-o", str(base),
            str(PROFILE_BIN), str(size), str(size), str(size), str(warmup)]
    print("profiling:", " ".join(cmd))
    subprocess.run(cmd, cwd=str(REPO), check=True)

    rep = str(base) + ".ncu-rep"
    txt = PROFILE_TXT_DIR / f"{name}.txt"
    csv = PROFILE_CSV_DIR / f"{name}.csv"
    with open(txt, "w") as f:
        subprocess.run([NCU, "-i", rep, "--page", "details",
                        "--print-details", "all"], stdout=f, check=True)
        f.write("\nSection: Warp Stall Breakdown (cycles/issue):\n")
        raw = subprocess.run([NCU, "-i", rep, "--page", "raw"],
                             capture_output=True, text=True, check=True)
        for line in raw.stdout.splitlines():
            if ("smsp__average_warps_issue_stalled_" in line
                    and "_per_issue_active.ratio" in line):
                f.write(line + "\n")
    with open(csv, "w") as f:
        subprocess.run([NCU, "-i", rep, "--csv", "--page", "details"],
                       stdout=f, check=True)
    print(f"wrote {rep}")
    print(f"      {txt}")
    print(f"      {csv}")


def profile_best(args) -> None:
    if not RESULTS_JSON.exists():
        print(f"error: {RESULTS_JSON} not found; run a search first",
              file=sys.stderr)
        sys.exit(1)
    records = json.loads(RESULTS_JSON.read_text())
    if not records:
        print(f"error: {RESULTS_JSON} is empty", file=sys.stderr)
        sys.exit(1)
    is_warp = "WM" in records[0]
    if is_warp != (args.kernel == "warp"):
        print(f"error: {RESULTS_JSON} holds {'warp' if is_warp else 'tunable'} "
              f"results, but --kernel={args.kernel} was given", file=sys.stderr)
        sys.exit(1)
    fields = WARP_FIELDS if args.kernel == "warp" else TUNE_FIELDS
    sizes = [int(s) for s in args.sizes.split(",") if s.strip()]
    for size in sizes:
        ok = [r for r in records if r["size"] == size and r["ok"]]
        if not ok:
            print(f"size={size}: no valid config in results.json; skipped",
                  file=sys.stderr)
            continue
        best = max(ok, key=lambda r: r["gflops"])
        desc = " ".join(f"{f}={best[f]}" for f in fields)
        print(f"size={size}: profiling best cfg {best['cfg']} "
              f"({best['gflops']:.1f} GFLOPS)  {desc}")
        if args.kernel == "warp":
            source = render_profile_warp(best)
        else:
            source = render_profile_tunable(best, args.vec)
        AUTOTUNE_BUILD.mkdir(parents=True, exist_ok=True)
        PROFILE_CU.write_text(source)
        compile_profile(args.nvcc, args.arch)
        run_profile(size, args.kernel, args.profile_warmup)


def main() -> None:
    ap = argparse.ArgumentParser(description="GEMM autotune search driver")
    ap.add_argument("--sizes", default=",".join(map(str, DEFAULT_SIZES)),
                    help="comma-separated problem sizes (M=N=K)")
    ap.add_argument("--kernel", choices=("tunable", "warp"), default="tunable",
                    help="which kernel to autotune")
    ap.add_argument("--vec", type=int, default=1, choices=(0, 1),
                    help="VEC_CONFIG value (tunable kernel only)")
    ap.add_argument("--repeat", type=int, default=20, help="timing iterations")
    ap.add_argument("--nvcc", default=DEFAULT_NVCC)
    ap.add_argument("--arch", default=DEFAULT_ARCH)
    ap.add_argument("--smem-kb", type=int, default=48,
                    help="static shared-mem budget in KB")
    ap.add_argument("--profile-best", action="store_true",
                    help="profile the best config from results.json via ncu "
                         "(ncu needs root: run 'sudo python search.py --profile-best ...')")
    ap.add_argument("--profile-warmup", type=int, default=10,
                    help="warmup iterations inside the profile binary")
    args = ap.parse_args()

    if args.profile_best:
        profile_best(args)
        return

    sizes = [int(s) for s in args.sizes.split(",") if s.strip()]
    dev = constraints.Device(shared_mem_per_block=args.smem_kb * 1024)

    if args.kernel == "warp":
        cfgs = list(constraints.gen_warp_configs(device=dev))
        fields = WARP_FIELDS
        source = render_warp(cfgs)
    else:
        cfgs = list(constraints.gen_configs(vec=bool(args.vec), device=dev))
        fields = TUNE_FIELDS
        source = render_tunable(cfgs, args.vec)

    print(f"{len(cfgs)} valid configs (kernel={args.kernel})")

    AUTOTUNE_BUILD.mkdir(parents=True, exist_ok=True)
    BENCH_CU.write_text(source)
    compile_bench(args.nvcc, args.arch)

    results = []
    for size in sizes:
        recs = run_bench(size, args.repeat, fields)
        results.extend(recs)
        ok = [r for r in recs if r["ok"]]
        best = max(ok, key=lambda r: r["gflops"]) if ok else None
        summary = (f"best={best['gflops']:.1f} GFLOPS (cfg {best['cfg']})"
                   if best else "no valid config")
        print(f"size={size}: {len(recs)} configs, "
              f"{len(recs) - len(ok)} failed, {summary}")

    RESULTS_JSON.write_text(json.dumps(results, indent=2))
    print(f"wrote {RESULTS_JSON}")


if __name__ == "__main__":
    main()
