#!/usr/bin/env python3
"""Search driver for the GEMM autotuner.

Strategy (single-compile + runtime switch): the tunable kernel is templated on
compile-time ints, so we cannot enumerate configs in a runtime loop.  Instead
we *generate* one self-contained ``.cu`` whose ``launch(cfg, ...)`` switches
over every valid config, compile it once, run it once per problem size, and
parse per-config GFLOPS from stdout into ``results.json``.

Usage::

    python search.py                        # default sizes, vec=1
    python search.py --sizes 256,512,1024 --vec 1 --repeat 20
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]  # scripts/autotune/GEMM -> repo root
sys.path.insert(0, str(HERE))

import constraints  # noqa: E402

BENCH_CU = HERE / "autotune_bench.cu"
BENCH_BIN = HERE / "autotune_bench"
RESULTS_JSON = HERE / "results.json"
KERNEL_INCLUDE = "GEMM/7_autotune.cuh"

DEFAULT_SIZES = (128, 256, 512, 1024, 2048, 4096)
DEFAULT_NVCC = "/usr/local/cuda-13.3/bin/nvcc"
DEFAULT_ARCH = "sm_120"


def render_bench(cfgs, vec: int) -> str:
    """Render the generated benchmark source."""
    lines = []
    lines.append("// Auto-generated by scripts/autotune/GEMM/search.py. Do not edit.")
    lines.append("#include <cmath>")
    lines.append("#include <cstdio>")
    lines.append("#include <cstdlib>")
    lines.append("")
    lines.append(f"#define VEC_CONFIG {vec}")
    lines.append(f'#include "{KERNEL_INCLUDE}"')
    lines.append("")

    # Config table (mirrors the switch below, used for reporting).
    lines.append("struct CfgInfo { int threads, BM, BN, BK, TM, TN; };")
    lines.append("static const CfgInfo CFG[] = {")
    for c in cfgs:
        lines.append(f"    {{{c.threads}, {c.BM}, {c.BN}, {c.BK}, {c.TM}, {c.TN}}},")
    lines.append("};")
    lines.append("static const int NUM_CONFIGS = (int)(sizeof(CFG) / sizeof(CFG[0]));")
    lines.append("")

    # Dispatch switch: one case per compile-time config.
    lines.append("static void launch(int cfg, int M, int N, int K, float alpha,")
    lines.append("                   float *A, float *B, float beta, float *C) {")
    lines.append("    switch (cfg) {")
    for i, c in enumerate(cfgs):
        lines.append(f"        case {i}: {{")
        lines.append(
            f"            constexpr int T = {c.threads}, BM = {c.BM}, BN = {c.BN}, "
            f"BK = {c.BK}, TM = {c.TM}, TN = {c.TN};"
        )
        lines.append("            dim3 grid((M + BM - 1) / BM, (N + BN - 1) / BN);")
        lines.append(
            "            gemm_tunable<T, BM, BN, BK, TM, TN>"
            "<<<grid, T>>>(M, N, K, alpha, A, B, beta, C);"
        )
        lines.append("            break;")
        lines.append("        }")
    lines.append("        default: break;")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # CPU reference + tolerance check.
    lines.append("static float randf() { return (float)(rand() % 1000) / 100.0f - 5.0f; }")
    lines.append("")
    lines.append("static void gemm_cpu(int M, int N, int K, float alpha, const float *A,")
    lines.append("                     const float *B, float beta, const float *C0, float *Cref) {")
    lines.append("    for (int i = 0; i < M; ++i)")
    lines.append("        for (int j = 0; j < N; ++j) {")
    lines.append("            float s = 0.0f;")
    lines.append("            for (int k = 0; k < K; ++k) s += A[i * K + k] * B[k * N + j];")
    lines.append("            Cref[i * N + j] = alpha * s + beta * C0[i * N + j];")
    lines.append("        }")
    lines.append("}")
    lines.append("")
    lines.append("static bool close_enough(const float *a, const float *b, int n) {")
    lines.append("    for (int i = 0; i < n; ++i) {")
    lines.append("        float diff = fabsf(a[i] - b[i]);")
    lines.append("        float thre = 1e-4f * fabsf(b[i]) + 1e-3f;")
    lines.append("        if (diff > thre) return false;")
    lines.append("    }")
    lines.append("    return true;")
    lines.append("}")
    lines.append("")

    lines.append("int main(int argc, char **argv) {")
    lines.append("    if (argc < 4) { fprintf(stderr, \"usage: %s M N K [repeat]\\n\", argv[0]); return 1; }")
    lines.append("    int M = atoi(argv[1]), N = atoi(argv[2]), K = atoi(argv[3]);")
    lines.append("    int repeat = argc > 4 ? atoi(argv[4]) : 20;")
    lines.append("    float alpha = 0.5f, beta = 3.0f;")
    lines.append("")
    lines.append("    size_t szA = (size_t)M * K, szB = (size_t)K * N, szC = (size_t)M * N;")
    lines.append("    float *A = (float*)malloc(szA * sizeof(float));")
    lines.append("    float *B = (float*)malloc(szB * sizeof(float));")
    lines.append("    float *C0 = (float*)malloc(szC * sizeof(float));")
    lines.append("    float *Cref = (float*)malloc(szC * sizeof(float));")
    lines.append("    float *C = (float*)malloc(szC * sizeof(float));")
    lines.append("    srand(42);")
    lines.append("    for (size_t i = 0; i < szA; ++i) A[i] = randf();")
    lines.append("    for (size_t i = 0; i < szB; ++i) B[i] = randf();")
    lines.append("    for (size_t i = 0; i < szC; ++i) C0[i] = randf();")
    lines.append("")
    lines.append("    float *dA, *dB, *dC;")
    lines.append("    cudaMalloc(&dA, szA * sizeof(float));")
    lines.append("    cudaMalloc(&dB, szB * sizeof(float));")
    lines.append("    cudaMalloc(&dC, szC * sizeof(float));")
    lines.append("    cudaMemcpy(dA, A, szA * sizeof(float), cudaMemcpyHostToDevice);")
    lines.append("    cudaMemcpy(dB, B, szB * sizeof(float), cudaMemcpyHostToDevice);")
    lines.append("    gemm_cpu(M, N, K, alpha, A, B, beta, C0, Cref);")
    lines.append("")
    lines.append("    cudaEvent_t beg, end;")
    lines.append("    cudaEventCreate(&beg); cudaEventCreate(&end);")
    lines.append("")
    lines.append("    for (int cfg = 0; cfg < NUM_CONFIGS; ++cfg) {")
    lines.append("        cudaMemcpy(dC, C0, szC * sizeof(float), cudaMemcpyHostToDevice);")
    lines.append("        launch(cfg, M, N, K, alpha, dA, dB, beta, dC);")
    lines.append("        cudaError_t err = cudaDeviceSynchronize();")
    lines.append("        if (err != cudaSuccess) {")
    lines.append("            printf(\"CFG %d %d %d %d %d %d %d 0.000000 0.0 ERROR(%s)\\n\",")
    lines.append("                   cfg, CFG[cfg].threads, CFG[cfg].BM, CFG[cfg].BN,")
    lines.append("                   CFG[cfg].BK, CFG[cfg].TM, CFG[cfg].TN, cudaGetErrorString(err));")
    lines.append("            fflush(stdout); continue;")
    lines.append("        }")
    lines.append("        cudaMemcpy(C, dC, szC * sizeof(float), cudaMemcpyDeviceToHost);")
    lines.append("        bool ok = close_enough(C, Cref, (int)szC);")
    lines.append("")
    lines.append("        cudaEventRecord(beg);")
    lines.append("        for (int j = 0; j < repeat; ++j) launch(cfg, M, N, K, alpha, dA, dB, beta, dC);")
    lines.append("        cudaEventRecord(end);")
    lines.append("        cudaEventSynchronize(end);")
    lines.append("        float ms = 0.0f; cudaEventElapsedTime(&ms, beg, end); ms /= repeat;")
    lines.append("        double gflops = 2.0 * (double)M * N * K / (ms * 1e-3) / 1e9;")
    lines.append("")
    lines.append("        printf(\"CFG %d %d %d %d %d %d %d %.6f %.1f %s\\n\",")
    lines.append("               cfg, CFG[cfg].threads, CFG[cfg].BM, CFG[cfg].BN, CFG[cfg].BK,")
    lines.append("               CFG[cfg].TM, CFG[cfg].TN, ms, gflops, ok ? \"OK\" : \"BAD\");")
    lines.append("        fflush(stdout);")
    lines.append("    }")
    lines.append("")
    lines.append("    free(A); free(B); free(C0); free(Cref); free(C);")
    lines.append("    cudaFree(dA); cudaFree(dB); cudaFree(dC);")
    lines.append("    cudaEventDestroy(beg); cudaEventDestroy(end);")
    lines.append("    return 0;")
    lines.append("}")
    return "\n".join(lines) + "\n"


def compile_bench(nvcc: str, arch: str) -> None:
    cmd = [
        nvcc,
        f"-arch={arch}",
        "-std=c++20",
        "-O3",
        "-I", str(REPO / "src"),
        "-o", str(BENCH_BIN),
        str(BENCH_CU),
    ]
    print("compiling:", " ".join(cmd))
    subprocess.run(cmd, cwd=str(REPO), check=True)


def run_bench(size: int, repeat: int) -> list[dict]:
    cmd = [str(BENCH_BIN), str(size), str(size), str(size), str(repeat)]
    proc = subprocess.run(cmd, cwd=str(REPO), capture_output=True, text=True)
    if proc.returncode != 0:
        print(proc.stderr, file=sys.stderr)
        raise RuntimeError(f"benchmark failed for size {size}")

    records = []
    for line in proc.stdout.splitlines():
        parts = line.split(maxsplit=10)
        if not parts or parts[0] != "CFG" or len(parts) < 11:
            continue
        cfg = int(parts[1]); threads = int(parts[2])
        bm = int(parts[3]); bn = int(parts[4]); bk = int(parts[5])
        tm = int(parts[6]); tn = int(parts[7])
        ms = float(parts[8]); gflops = float(parts[9])
        status = parts[10]
        records.append({
            "size": size,
            "cfg": int(cfg),
            "threads": int(threads),
            "BM": int(bm), "BN": int(bn), "BK": int(bk),
            "TM": int(tm), "TN": int(tn),
            "ms": float(ms),
            "gflops": float(gflops),
            "ok": status == "OK",
        })
    return records


def main() -> None:
    ap = argparse.ArgumentParser(description="GEMM autotune search driver")
    ap.add_argument("--sizes", default=",".join(map(str, DEFAULT_SIZES)),
                    help="comma-separated problem sizes (M=N=K)")
    ap.add_argument("--vec", type=int, default=1, choices=(0, 1),
                    help="VEC_CONFIG value (single compile, so fixed per run)")
    ap.add_argument("--repeat", type=int, default=20, help="timing iterations")
    ap.add_argument("--nvcc", default=DEFAULT_NVCC)
    ap.add_argument("--arch", default=DEFAULT_ARCH)
    ap.add_argument("--smem-kb", type=int, default=48,
                    help="static shared-mem budget in KB")
    args = ap.parse_args()

    sizes = [int(s) for s in args.sizes.split(",") if s.strip()]

    dev = constraints.Device(shared_mem_per_block=args.smem_kb * 1024)
    cfgs = list(constraints.gen_configs(vec=bool(args.vec), device=dev))
    print(f"{len(cfgs)} valid configs (vec={args.vec})")

    BENCH_CU.write_text(render_bench(cfgs, args.vec))
    compile_bench(args.nvcc, args.arch)

    results = []
    for size in sizes:
        recs = run_bench(size, args.repeat)
        results.extend(recs)
        ok = [r for r in recs if r["ok"]]
        best = max(ok, key=lambda r: r["gflops"]) if ok else None
        summary = (f"best={best['gflops']:.1f} GFLOPS (cfg {best['cfg']})"
                   if best else "no valid config")
        print(f"size={size}: {len(recs)} configs, "
              f"{len(recs) - len(ok)} failed, {summary}")

    RESULTS_JSON.write_text(json.dumps(results, indent=2))
    print(f"wrote {RESULTS_JSON}")


if __name__ == "__main__":
    main()
